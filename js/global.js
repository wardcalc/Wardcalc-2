/* =========================================================
   LANGUAGE ENGINE
========================================================= */

let currentLang =
  localStorage.getItem("wardcalc_lang") || "en";

/* =========================================================
   GET TRANSLATION
========================================================= */

function t(key) {

  return (
    T[currentLang]?.[key] ||
    T.en[key] ||
    key
  );
}

/* =========================================================
   APPLY TRANSLATIONS
========================================================= */

function applyTranslations() {

  document
    .querySelectorAll("[data-i18n]")
    .forEach(el => {

      const key =
        el.dataset.i18n;

      if (
        T[currentLang] &&
        T[currentLang][key]
      ) {

        el.innerHTML =
          T[currentLang][key];
      }
    });

  /* Active button */

  document
    .querySelectorAll(".lang-btn")
    .forEach(btn => {

      btn.classList.remove("active");

      if (
        btn.dataset.lang === currentLang
      ) {

        btn.classList.add("active");
      }
    });
}

/* =========================================================
   SET LANGUAGE
========================================================= */

function setLanguage(lang) {

  currentLang = lang;

  localStorage.setItem(
    "wardcalc_lang",
    lang
  );

  applyTranslations();
}

/* =========================================================
   AUTO LOAD
========================================================= */

document.addEventListener(
  "DOMContentLoaded",
  () => {

    applyTranslations();
  }
);
